#!/usr/bin/env python3
"""Embed the mod's own content bytes in the native source archive."""
from pathlib import Path
import hashlib,json
ROOT=Path(__file__).resolve().parents[1]
files=[(p.relative_to(ROOT/'content').as_posix(),p.read_bytes()) for p in sorted((ROOT/'content').rglob('*')) if p.is_file() and (p.name == 'horizon-mod.toml' or p.relative_to(ROOT/'content').parts[0] in ('assets', 'data'))]
# Horizon's pinned StartChecks has no extension field. Carry our two named predicates
# in an otherwise unrestricted upper height bound. Without the hook both bounds are
# above the world's build ceiling and harmless to Horizon's own terrain checks.
def structure_checks(path, raw):
    if "/worldgen/structure/" not in path or not path.endswith(".json"):
        return raw
    structure = json.loads(raw)
    checks = structure.get("horizon:start_checks", {})
    site = checks.pop("strangely_charming:site", None)
    if site is None:
        return raw
    if "max_y" in checks:
        raise ValueError(f"{path}: site check already supplies max_y")
    checks["max_y"] = {"circle": 2147483646, "buried": 2147483645}[site]
    return (json.dumps(structure, indent=2) + "\n").encode()
files = [(path, structure_checks(path, raw)) for path, raw in files]
digest=hashlib.sha256(b''.join(n.encode()+b for n,b in files)).hexdigest()
source='// Generated by tools/embed_content.py; edit content/ instead.\n'
source+='pub const FILES: &[(&str, &[u8])] = &[\n'
for name,data in files:source+=f'({json.dumps(name)}, &{list(data)}),\n'
source+='];\n'
source+='''pub fn merchant_files(files: &mut Vec<(String, Vec<u8>)>) {
    for (path, bytes) in FILES {
        let Some(relative) = path.strip_prefix("data/strangely_charming/") else { continue };
        let Some((registry, name)) = relative.split_once('/') else { continue };
        if !matches!(registry, "villager_trade" | "trade_set") { continue; }
        let feature = if name.starts_with("scrollkeeper/") { "scrollkeepers" } else if name.starts_with("beekeeper/") { "beekeepers" } else { "lumberjacks" };
        if crate::evanders_config::enabled(feature) {
            let id = name.trim_end_matches(".json");
            files.push((format!("{registry}/strangely_charming:{id}"), bytes.to_vec()));
        }
    }
}
pub fn install(dir: &std::path::Path) -> Result<std::path::PathBuf, std::io::Error> {
    let root = dir.parent().unwrap_or(dir).join(".horizon-cache").join("strangely-charming-CONTENT_HASH");
    let features = ["extra_recipes", "poison_apple", "crying_obsidian_frames","raid_horns","ender_pearl_blocks","kilns","exploration_advancements","lumberjacks","beekeepers","coral_squids","portable_crafting","extract_enchantments","grindable_armor","inventory_totem","moonstones","enchanting_totems","scrollkeepers","runebreaker","rune_circles","underground_ruins"];
    let variant = features.iter().enumerate().fold(0u32, |mask,(i,k)| mask | (u32::from(crate::evanders_config::enabled(k)) << i));
    let root = root.with_extension(format!("cfg-{variant}"));
    for (name, bytes) in FILES {
        if name.contains("/advancement/discovery/") && !crate::evanders_config::enabled("exploration_advancements") { continue; }
        let discovery = name.split_once("/advancement/discovery/").and_then(|(_,leaf)| leaf.strip_suffix(".json"));
        if discovery.is_some_and(|key| key != "root" && !crate::evanders_config::enabled(key)) {continue;}
        let feature = if name.ends_with("/structure_set/rune_circle.json") {Some("rune_circles")} else if name.ends_with("/structure_set/underground_ruins.json") || name.ends_with("/structure_set/nether_ruins.json") {Some("underground_ruins")} else if name.contains("/runebreaker/") {Some("runebreaker")} else if name.contains("/scrollkeepers/") || name.contains("/scrollkeeper/") {Some("scrollkeepers")} else if name.contains("/biome_modifier/moonstone") {Some("moonstones")} else if name.contains("/lumberjacks/") || name.contains("/lumberjack/") {Some("lumberjacks")}
            else if name.contains("/beekeeper/") {Some("beekeepers")}
            else if name.contains("/kilns/") || name.ends_with("/discovery/kilns.json") {Some("kilns")}
            else if name.ends_with("/discovery/raid_horns.json") {Some("raid_horns")}
            else if name.contains("/ender_pearl_blocks/") || name.ends_with("/discovery/ender_pearl_blocks.json") || name.ends_with("/entities_can_teleport_to.json") {Some("ender_pearl_blocks")}
            else if name.contains("/extra_recipes/") { Some("extra_recipes") }
            else if (name.contains("/recipe/") || name.contains("/advancement/")) && (name.ends_with("/poison_apple.json") || name.ends_with("/tweaks.json")) { Some("poison_apple") }
            else if name.ends_with("/nether_portal_frame.json") { Some("crying_obsidian_frames") }
            else { None };
        if name.contains("/creative_tab/") && let Some(key) = name.rsplit('/').next().and_then(|v|v.strip_suffix(".json")) && key!="tweaks" && !crate::evanders_config::enabled(key) {continue;}
        if feature.is_some_and(|key| !crate::evanders_config::enabled(key)) { continue; }
        let path = root.join(name);
        let creative;
        let bytes = if name.ends_with("/creative_tab/tweaks.json") {
            let mut items: Vec<_> = [("runebreaker","runebreaker"),("poison_apple","poison_apple"),("raid_horns","raid_horn"),("kilns","kiln"),("ender_pearl_blocks","ender_pearl_block"),("lumberjacks","woodcutter")].into_iter()
                .filter(|(k,_)|crate::evanders_config::enabled(k)).map(|(_,item)|format!("strangely_charming:{item}")).collect();
            if crate::evanders_config::enabled("moonstones") {
                for color in ["white", "orange", "magenta", "light_blue", "yellow", "lime", "pink", "gray", "light_gray", "cyan", "purple", "blue", "brown", "green", "red", "black"] {items.push(format!("strangely_charming:moonstone_{color}"));}
            }
            if crate::evanders_config::enabled("enchanting_totems"){items.push("strangely_charming:totem_of_enchanting".into());}
            if crate::evanders_config::enabled("scrollkeepers"){
                for id in ["writing_desk","scroll_wheat","scroll_bread","scroll_coal","scroll_zombies","scroll_books"] {items.push(format!("strangely_charming:{id}"));}
            }
            if items.is_empty(){continue;}
            creative=serde_json::to_vec(&serde_json::json!({"title":"Strangely Charming","icon":"strangely_charming:mod_icon","items":items}))?;
            creative.as_slice()
        } else { *bytes };
        if std::fs::read(&path).is_ok_and(|existing| existing == bytes) { continue; }
        if let Some(parent) = path.parent() { std::fs::create_dir_all(parent)?; }
        let temporary = path.with_extension(format!("tmp-{}", std::process::id()));
        std::fs::write(&temporary, bytes)?;
        std::fs::rename(temporary, path)?;
    }
    Ok(root)
}
'''.replace('CONTENT_HASH',digest[:16])
(ROOT/'mixins/strangely_charming/content_bundle.rs').write_text(source)
